
-- Create the raw Spotify tracks table

CREATE TABLE IF NOT EXISTS SPOTIFY_ANALYTICS_DB.RAW.SPOTIFY_TRACKS (

    SOURCE_ROW_ID NUMBER(10,0),

    ACOUSTICNESS FLOAT,
    DANCEABILITY FLOAT,
    DURATION_MS NUMBER(12,0),
    ENERGY FLOAT,
    INSTRUMENTALNESS FLOAT,
    MUSICAL_KEY NUMBER(2,0),
    LIVENESS FLOAT,
    LOUDNESS FLOAT,
    MODE NUMBER(1,0),
    SPEECHINESS FLOAT,
    TEMPO FLOAT,
    TIME_SIGNATURE NUMBER(1,0),
    VALENCE FLOAT,
    TARGET NUMBER(1,0),

    SONG_TITLE VARCHAR(500),
    ARTIST VARCHAR(500)

);



DESCRIBE TABLE SPOTIFY_ANALYTICS_DB.RAW.SPOTIFY_TRACKS;