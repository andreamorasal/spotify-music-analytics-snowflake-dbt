-- Create the project database

CREATE DATABASE IF NOT EXISTS SPOTIFY_ANALYTICS_DB;


-- Create the project warehouse

CREATE WAREHOUSE IF NOT EXISTS SPOTIFY_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;


-- Create the RAW schema

CREATE SCHEMA IF NOT EXISTS SPOTIFY_ANALYTICS_DB.RAW;